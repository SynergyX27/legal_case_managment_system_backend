export const permissionKeys = permissionActions.map(([key]) => key);
export const profileFor = (id) => roleProfiles.find((p) => p.id === id);

export function eligiblePermission(base, key) {
  if (key === "permissions.manage") return false;
  if (
    [
      "users.manage",
      "workspaces.manage",
      "company.manage",
      "settings.manage",
      "team.assign_managers",
    ].includes(key)
  )
    return base === "owner";
  if (key === "team.assign") return ["owner", "manager"].includes(base);
  return true;
}
